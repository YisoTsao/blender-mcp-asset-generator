"""Forest Valley -> Unreal Engine 5 import (run inside the Unreal Editor:
Tools > Execute Python Script, with the Python Editor Script Plugin enabled).

NOTE: generated by the Blender pipeline; this script has NOT been executed in Unreal here
(no Unreal Engine on the build machine). Review before use on a production project.

Steps performed:
  1. import every FBX in Meshes/ (LOD0) and attach LOD1..n; Nanite on rocks / structures
  2. per World Partition cell, spawn one actor with one HISM component per mesh
  3. gameplay: PlayerStart per team spawn (tags), TargetPoints for objectives / pickups / cover
  4. lighting: DirectionalLight, SkyAtmosphere, SkyLight, ExponentialHeightFog, VolumetricCloud
     configured from the chosen preset in Data/lighting_presets.json
The Landscape itself is imported with the Landscape tool (values in README_UE_IMPORT.md).
"""
import json
import os

import unreal

ROOT = os.path.dirname(os.path.abspath(__file__))
DEST = "/Game/ForestValley"
PRESET = "noon"

asset_tools = unreal.AssetToolsHelpers.get_asset_tools()
eal = unreal.EditorAssetLibrary
actors = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)


def load(name):
    with open(os.path.join(ROOT, "Data", name)) as f:
        return json.load(f)


def import_fbx(path, dest):
    task = unreal.AssetImportTask()
    task.filename = path
    task.destination_path = dest
    task.automated = True
    task.replace_existing = True
    task.save = True
    opts = unreal.FbxImportUI()
    opts.import_mesh = True
    opts.import_materials = False
    opts.import_textures = False
    opts.static_mesh_import_data.combine_meshes = True
    opts.static_mesh_import_data.auto_generate_collision = False
    task.options = opts
    asset_tools.import_asset_tasks([task])
    return [eal.load_asset(p) for p in task.imported_object_paths]


def import_meshes(manifest):
    meshes = {}
    for name, info in manifest["assets"].items():
        lods = info["lods"]
        dest = f"{DEST}/Meshes/{info['category']}"
        sm = import_fbx(os.path.join(ROOT, lods[0]["file"]), dest)
        if not sm:
            continue
        sm = sm[0]
        for k, lod in enumerate(lods[1:], start=1):
            unreal.EditorStaticMeshLibrary.import_lod(sm, k, os.path.join(ROOT, lod["file"]))
        if info["nanite_candidate"]:
            ns = sm.get_editor_property("nanite_settings")
            ns.enabled = True
            sm.set_editor_property("nanite_settings", ns)
        meshes[name] = sm
        eal.save_loaded_asset(sm)
    return meshes


def spawn_cells(meshes, manifest):
    folder = os.path.join(ROOT, "Data", "cells")
    for fn in sorted(os.listdir(folder)):
        cell = json.load(open(os.path.join(folder, fn)))
        actor = actors.spawn_actor_from_class(unreal.Actor, unreal.Vector(0, 0, 0))
        actor.set_actor_label(f"FV_{fn[:-5]}")
        actor.set_folder_path("ForestValley/Cells")
        for name, rows in cell["instances"].items():
            sm = meshes.get(name)
            if not sm:
                continue
            comp = unreal.HierarchicalInstancedStaticMeshComponent(actor, name)
            comp.set_static_mesh(sm)
            cull = manifest["assets"][name].get("cull_distance_m")
            if cull:
                comp.set_cull_distances(0, int(cull * 100))
            for x, y, z, roll, pitch, yaw, s in rows:
                t = unreal.Transform(unreal.Vector(x, y, z), unreal.Rotator(roll, pitch, yaw), unreal.Vector(s, s, s))
                comp.add_instance(t)


def spawn_gameplay(gp):
    def v(p):
        return unreal.Vector(p[0] * 100, -p[1] * 100, p[2] * 100)
    for team, pts in gp["spawns"]["team"].items():
        for s in pts:
            a = actors.spawn_actor_from_class(unreal.PlayerStart, v(s["pos_m"]) + unreal.Vector(0, 0, 100),
                                              unreal.Rotator(0, 0, -s["yaw_deg"]))
            a.set_editor_property("player_start_tag", team)
            a.set_folder_path("ForestValley/Gameplay/Spawns")
    for o in gp["objectives"]:
        a = actors.spawn_actor_from_class(unreal.TargetPoint, v(o["pos_m"]))
        a.set_actor_label(f"Objective_{o['id']}_{o['name']}")
        a.tags = [unreal.Name("objective"), unreal.Name(o["id"])]
        a.set_folder_path("ForestValley/Gameplay/Objectives")
    for i, p in enumerate(gp["pickups"]):
        a = actors.spawn_actor_from_class(unreal.TargetPoint, v(p["pos_m"]))
        a.set_actor_label(f"Pickup_{p['type']}_{i:03d}")
        a.tags = [unreal.Name("pickup"), unreal.Name(p["type"])]
        a.set_folder_path("ForestValley/Gameplay/Pickups")


def spawn_lighting(preset):
    p = preset["unreal"]
    rot = p["directional_light_rotation_deg"]
    sun = actors.spawn_actor_from_class(unreal.DirectionalLight, unreal.Vector(0, 0, 50000),
                                        unreal.Rotator(0, rot["pitch"], rot["yaw"]))
    lc = sun.light_component
    lc.set_editor_property("use_temperature", True)
    lc.set_editor_property("temperature", p["color_temperature_k"])
    lc.set_editor_property("intensity", p.get("sun_lux", p.get("moon_lux", 1.0)))
    lc.set_editor_property("atmosphere_sun_light", True)
    actors.spawn_actor_from_class(unreal.SkyAtmosphere, unreal.Vector(0, 0, 0))
    sky = actors.spawn_actor_from_class(unreal.SkyLight, unreal.Vector(0, 0, 1000))
    sky.light_component.set_editor_property("real_time_capture", True)
    fog = actors.spawn_actor_from_class(unreal.ExponentialHeightFog, unreal.Vector(0, 0, 0))
    fc = fog.component
    fc.set_editor_property("fog_density", p["height_fog_density"])
    fc.set_editor_property("fog_height_falloff", p["height_fog_falloff"])
    fc.set_editor_property("volumetric_fog", p["volumetric_fog"])
    actors.spawn_actor_from_class(unreal.VolumetricCloud, unreal.Vector(0, 0, 0))


manifest = load("asset_manifest.json")
meshes = import_meshes(manifest)
spawn_cells(meshes, manifest)
spawn_gameplay(load("gameplay.json"))
spawn_lighting(load("lighting_presets.json")["presets"][PRESET])
unreal.log("Forest Valley import finished")
